#!/usr/bin/env node
// upskilling/_tools/build-index.mjs
//
// 1. Reads the front matter of every upskilling/04-journal/J*.md and rewrites
//    upskilling/04-journal/INDEX.md, sorted by J number.
// 2. Checks every code anchor in upskilling/**/*.md (except _audits/ and _templates/):
//      `path › symbol @ sha`   or   `path › symbol (Lx–y @ sha)`
//    (backticks around path and symbol are optional). `git show sha:path` must
//    succeed and its text must contain the symbol.
// Exits 1 if any front matter is invalid or any anchor fails.
//
// Usage (from the repo root):
//   node upskilling/_tools/build-index.mjs            rewrite INDEX.md, check anchors
//   node upskilling/_tools/build-index.mjs --check    do not write; exit 1 if INDEX.md is stale
//   node upskilling/_tools/build-index.mjs --no-anchors
// No dependencies; Node 20+.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const upskilling = resolve(here, '..');
const repoRoot = resolve(upskilling, '..');
const journalDir = join(upskilling, '04-journal');
const indexPath = join(journalDir, 'INDEX.md');

const args = new Set(process.argv.slice(2));
const checkOnly = args.has('--check');
const skipAnchors = args.has('--no-anchors');

const failures = [];
const fail = (msg) => failures.push(msg);
const rel = (p) => relative(repoRoot, p).split(sep).join('/');

// ---------- front matter ----------

const REQUIRED = ['id', 'title', 'area', 'closes', 'ladder', 'adrs', 'status'];
const STATUSES = new Set(['draft', 'in review', 'landed']);
const AREAS = new Set(['server', 'client', 'content', 'tooling']);

function unquote(s) {
  return /^(['"]).*\1$/.test(s) ? s.slice(1, -1) : s;
}

function parseValue(raw) {
  const v = raw.trim();
  if (v.startsWith('[') && v.endsWith(']')) {
    const inner = v.slice(1, -1).trim();
    return inner === '' ? [] : inner.split(',').map((s) => unquote(s.trim())).filter(Boolean);
  }
  return unquote(v);
}

function parseFrontMatter(text, file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
  if (!m) {
    fail(`${rel(file)}: no front matter block (--- ... ---) at the top`);
    return null;
  }
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const kv = /^([A-Za-z_]+)\s*:\s*(.*)$/.exec(line);
    if (!kv) {
      fail(`${rel(file)}: cannot parse front matter line "${line}"`);
      continue;
    }
    data[kv[1]] = parseValue(kv[2]);
  }
  for (const key of REQUIRED) {
    if (!(key in data)) fail(`${rel(file)}: front matter is missing "${key}"`);
  }
  for (const key of ['closes', 'ladder', 'adrs']) {
    if (key in data && !Array.isArray(data[key])) {
      fail(`${rel(file)}: "${key}" must be an inline list like [F-02, F-03] ([] when empty)`);
    }
  }
  if (data.status && !STATUSES.has(data.status)) {
    fail(`${rel(file)}: status "${data.status}" is not one of ${[...STATUSES].join(', ')}`);
  }
  if (data.area) {
    for (const a of String(data.area).split('+')) {
      if (!AREAS.has(a.trim())) fail(`${rel(file)}: area "${data.area}" uses unknown area "${a.trim()}"`);
    }
  }
  const fileId = /^(J\d{2,3}[a-z]?)-/.exec(file.split(/[\\/]/).pop())?.[1];
  if (data.id && fileId && data.id !== fileId) {
    fail(`${rel(file)}: front matter id ${data.id} does not match the file name (${fileId})`);
  }
  return data;
}

const cell = (v) => {
  const s = Array.isArray(v) ? v.join(', ') : String(v ?? '');
  return (s === '' ? '–' : s).replace(/\|/g, '\\|');
};

function buildIndex() {
  const files = existsSync(journalDir)
    ? readdirSync(journalDir).filter((f) => /^J\d{2,3}[a-z]?-.+\.md$/.test(f))
    : [];
  const rows = [];
  for (const f of files) {
    const path = join(journalDir, f);
    const fm = parseFrontMatter(readFileSync(path, 'utf8'), path);
    if (!fm) continue;
    rows.push({ n: Number(/^J(\d+)/.exec(f)[1]), file: f, ...fm });
  }
  rows.sort((a, b) => a.n - b.n || a.file.localeCompare(b.file));
  const seen = new Map();
  for (const r of rows) {
    const fileId = /^(J\d{2,3}[a-z]?)-/.exec(r.file)[1];
    if (seen.has(fileId)) fail(`04-journal: ${fileId} is used by both ${seen.get(fileId)} and ${r.file}`);
    seen.set(fileId, r.file);
  }

  const landed = rows.filter((r) => r.status === 'landed').length;
  const lines = [
    '# Journal index',
    '',
    '<!-- Generated by upskilling/_tools/build-index.mjs from each entry\'s front matter. Do not edit by hand; run `node upskilling/_tools/build-index.mjs`. -->',
    '',
    'Read in J-number order: tooling first, then server correctness, client, content, features. Rules and the numbered plan: [README.md](README.md). Register: [../10-findings-register.md](../10-findings-register.md).',
    '',
    '| # | Title | Area | Closes | Ladder | ADRs | Status |',
    '|---|---|---|---|---|---|---|',
    ...rows.map(
      (r) =>
        `| ${cell(r.id)} | [${cell(r.title)}](${r.file}) | ${cell(r.area)} | ${cell(r.closes)} | ${cell(r.ladder)} | ${cell(r.adrs)} | ${cell(r.status)} |`,
    ),
  ];
  if (rows.length === 0) lines.push('', '_No entries yet. See README.md for the numbered list; J08 is the seed example._');
  lines.push('', `${rows.length} ${rows.length === 1 ? 'entry' : 'entries'}, ${landed} landed.`, '');
  return { text: lines.join('\n'), count: rows.length };
}

// ---------- anchors ----------

// `path` › `symbol` (L12–30 @ 6f1bf43)   |   path › symbol @ 6f1bf43
const ANCHOR =
  /`?((?:[\w.@-]+\/)*[\w.@-]+\.[A-Za-z]{1,5})`?\s*›\s*`?([^`\n@()]+?(?:\(\))?)`?\s*(?:\(\s*(?:L[\d–\-, L]+?\s*)?@\s*([0-9a-f]{7,40})\s*\)|@\s*([0-9a-f]{7,40})\b)/g;

const blobCache = new Map();
function blob(sha, path) {
  const key = `${sha}:${path}`;
  if (!blobCache.has(key)) {
    try {
      blobCache.set(
        key,
        execFileSync('git', ['show', key], {
          cwd: repoRoot,
          encoding: 'utf8',
          stdio: ['ignore', 'pipe', 'ignore'],
          maxBuffer: 64 * 1024 * 1024,
        }),
      );
    } catch {
      blobCache.set(key, null);
    }
  }
  return blobCache.get(key);
}

function symbolCandidates(symbol) {
  const s = symbol.trim();
  const out = new Set([s]);
  const noParens = s.replace(/\(\)$/, '');
  out.add(noParens);
  // "POST /answers" -> "/answers"; "GET /modules/:id" -> "/modules/:id"
  const route = /^(?:GET|POST|PUT|PATCH|DELETE)\s+(\S+)$/.exec(noParens);
  if (route) out.add(route[1]);
  // "store.close" -> "close" (a method named through its object)
  if (/^[\w$]+\.[\w$]+$/.test(noParens)) out.add(noParens.split('.').pop());
  return [...out].filter(Boolean);
}

function markdownFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name === '_audits' || name === '_templates' || name === 'node_modules') continue;
      out.push(...markdownFiles(p));
    } else if (name.endsWith('.md')) out.push(p);
  }
  return out;
}

function checkAnchors() {
  let count = 0;
  for (const file of markdownFiles(upskilling)) {
    const lines = readFileSync(file, 'utf8').split(/\r?\n/);
    lines.forEach((line, i) => {
      for (const m of line.matchAll(ANCHOR)) {
        count++;
        const [, path, symbol, sha1, sha2] = m;
        const sha = sha1 ?? sha2;
        const where = `${rel(file)}:${i + 1}`;
        const content = blob(sha, path);
        if (content == null) {
          fail(`${where}: \`git show ${sha}:${path}\` failed (wrong path or sha) in "${m[0]}"`);
          continue;
        }
        if (!symbolCandidates(symbol).some((c) => content.includes(c))) {
          fail(`${where}: ${path} @ ${sha} does not contain "${symbol.trim()}"`);
        }
      }
    });
  }
  return count;
}

// ---------- main ----------

const { text, count } = buildIndex();
if (checkOnly) {
  const current = existsSync(indexPath) ? readFileSync(indexPath, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) fail(`${rel(indexPath)} is stale; run node upskilling/_tools/build-index.mjs`);
} else {
  writeFileSync(indexPath, text);
}
console.log(`${checkOnly ? 'checked' : 'wrote'} ${rel(indexPath)} (${count} entries)`);

if (!skipAnchors) console.log(`checked ${checkAnchors()} anchors`);

if (failures.length) {
  console.error(`\n${failures.length} problem${failures.length === 1 ? '' : 's'}:`);
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
}
console.log('ok');
